// Team brand colors for the TeamLogo component. Keys are the SHORT team names
// already produced by utils/teamNameConverter.ts / utils/teamSlugUtils.ts
// (e.g. "Brewers", not "Milwaukee Brewers") -- except NCAAF_COLORS/NCAAB_COLORS,
// which are keyed by the team-code abbreviation (e.g. "ALA") since that's what
// convertTeamNameNcaaf/convertTeamNameNcaab produce for college teams instead of
// a mascot short name. Every team in teamSlugUtils.ts's NCAAF_TEAMS/NCAAB_TEAMS
// maps has an entry here.
//
// SOCCER_COLORS is keyed by the full club name exactly as stored in the
// soccer_games table (e.g. "Paris Saint Germain") -- convertTeamNameEpl and the
// generic fallback converter don't shorten soccer names at all, unlike every
// other sport here, so the odds/historical name passes straight through
// unchanged. Covers every club that appeared in the app's own game data for
// the 5 supported leagues (EPL, La Liga, Bundesliga, Ligue 1, Serie A) across
// the last two seasons as of when this table was built -- a newly promoted
// club the app hasn't seen a game for yet will fall back to the neutral gray
// entry until it shows up in the data and gets added here.

export interface TeamColorEntry {
  primary: string;
  secondary: string;
  abbr: string;
}

